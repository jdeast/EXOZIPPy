"""Tabulate MIST stellar lifetimes for the present-day lens mass function.

Writes ``src/exozippy/components/galacticmodel/mist_lifetimes.csv``: the age
(Gyr) at the LAST point of each MIST v2.5 track in the shipped EEP grid
(``afe_p0_vvcrit0.0.grid.parquet``, EEP 807, one point before the TP-AGB
onset for low/intermediate mass stars and the end of core carbon burning for
massive ones), per initial mass and initial [Fe/H].  The TP-AGB and later
phases are ~1% of a life, so this is the lifetime tau(M_ini, [Fe/H]) to
that precision, and its inverse at fixed age is the dying (turnoff) mass
M_die(T, [Fe/H]) the present-day mass function needs (review 1.7.2).

Shorter tracks are padded to 807 rows by repeating their last row
(generate_MIST_EEP_Tables._pad_or_trim_df), so EEP 807's age is the track's
last age either way.  The lowest masses run to 90-3300 Gyr (here_be_dragons
rows) -- alive for any Galactic age, which is all that matters here.

Committed as a small CSV so a microlensing fit does not need the 123 MB
grid.  Rerun this script (from the repo root, with the grid present) after
a grid republish:

    PYTHONPATH=src python scripts/make_mist_lifetimes.py
"""

from pathlib import Path

import numpy as np
import pyarrow.parquet as pq

from exozippy.components.evolutionarymodel.mist_grid import grid_path

# The loader's trim is [-2.5, 0.5] (evolutionarymodel.md); +0.5 is left out
# because its 0.1 Msun track is a single row (lifetime 3 Myr against 3300
# Gyr at +0.25), and no Galactic population here is that metal rich.
FEH_RANGE = (-2.5, 0.25)
OUT = (
    Path(__file__).resolve().parents[1]
    / "src/exozippy/components/galacticmodel/mist_lifetimes.csv"
)


def main():
    path = grid_path()
    t = pq.read_table(
        str(path), columns=["mass", "EEP", "initfeh", "age_mist"]
    ).to_pandas()
    end = t[t.EEP == t.EEP.max()]
    fehs = sorted(
        f for f in end.initfeh.unique() if FEH_RANGE[0] <= f <= FEH_RANGE[1]
    )
    masses = np.sort(end.mass.unique())
    table = np.full((masses.size, len(fehs)), np.nan)
    for j, feh in enumerate(fehs):
        e = end[end.initfeh == feh].set_index("mass").age_mist
        table[:, j] = np.log10(e.reindex(masses).to_numpy() / 1e9)
    if not np.all(np.isfinite(table)):
        raise RuntimeError(f"{path}: a (mass, initfeh) track is missing")
    header = "mass," + ",".join(f"log10_life_gyr_feh{f:+.2f}" for f in fehs)
    body = np.column_stack([masses, table])
    np.savetxt(
        OUT,
        body,
        delimiter=",",
        fmt="%.6g",
        header=(
            f"MIST v2.5 lifetimes: log10(age at EEP {int(end.EEP.max())} / "
            f"Gyr) per initial mass (Msun) and initial [Fe/H].\n"
            f"Generated by scripts/make_mist_lifetimes.py from "
            f"{path.name}.\n{header}"
        ),
        comments="# ",
    )
    print(f"wrote {OUT} ({masses.size} masses x {len(fehs)} [Fe/H])")


if __name__ == "__main__":
    main()
