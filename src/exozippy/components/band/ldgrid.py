"""
The PHOENIX limb-darkening tables on the band side: which table a band
reads, how it is loaded onto its grid, and the one interpolation the
model and the start-value seed share -- the ``claret.py`` of the second
table source (``band.ld_source: phoenix``).

The tables are generated by ``models/PHOENIX/generate_PHOENIX_LD_Tables.py``
from the PHOENIX-ACES specific intensities (Husser et al. 2013) through
the SAME filter profiles, detector weighting and extinction law as the
NextGen bolometric corrections, and live in the BC tables' format
(``bc_grid.write_bc_table``): one parquet per facility and law under
``models/PHOENIX/LDs/{law}/``, columns ``teff logg feh alpha Av Rv`` plus
one column per coefficient (the MIST filter name for the linear law's
``u``; ``{name}__u1`` / ``{name}__u2`` for the quadratic law).  They have
FOUR axes: A_V is one, because reddening tilts the spectral weighting
inside a band (notes 2026-08-04; design in components/sed/sed.md, "The
limb-darkening tie").  Only the complete box of a table is loaded
(``bc_grid.complete_axes``), exactly as for a BC column.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Optional, Tuple

import numpy as np
import pandas as pd
import pytensor.tensor as pt
from scipy.interpolate import RegularGridInterpolator as _ScipyRGI

from exozippy.components.sed.bc_grid import (
    AMBIGUOUS_FILTER_ALIASES,
    DEFAULT_MODEL_ROOT,
    GRID_KEY_COLS,
    RegularGridInterpolator,
    _load_alias_table,
    bc_table_filter_columns,
    complete_axes,
    facility_from_svo_name,
    read_bc_table,
    resolve_filter_name,
)
from exozippy.models.PHOENIX.generate_PHOENIX_LD_Tables import (
    COEFFICIENTS,
    LAWS,
    coefficient_column,
    ld_table_path,
)

SOURCE = "PHOENIX"
AXIS_ORDER: Tuple[str, ...] = ("teff", "logg", "feh", "av")
_AXIS_KEY = {
    "teff": "teff_pts",
    "logg": "logg_pts",
    "feh": "feh_pts",
    "av": "av_pts",
}

# Read at CALL time (not bound as a default argument), so tests can point
# every reader at synthetic tables by patching this name.
DEFAULT_TABLE_ROOT: Optional[Path] = None


def _root(model_root) -> Path:
    if model_root is not None:
        return Path(model_root)
    return (
        Path(DEFAULT_TABLE_ROOT) if DEFAULT_TABLE_ROOT else DEFAULT_MODEL_ROOT
    )


@dataclass(frozen=True)
class LDTable:
    """One band's coefficients on a complete regular (teff, logg, feh, av)
    grid.  ``values`` has shape (n_teff, n_logg, n_feh, n_av,
    n_coefficients), the coefficients in ``columns`` order -- the layout
    ``bc_grid.RegularGridInterpolator`` interpolates directly."""

    band: str
    law: str
    columns: Tuple[str, ...]
    axes: Dict[str, np.ndarray]
    values: np.ndarray
    meta: Dict
    path: Path
    facility: str
    mist_name: str

    @property
    def axis_order(self) -> Tuple[str, ...]:
        return AXIS_ORDER

    @property
    def box(self) -> Dict[str, Tuple[float, float]]:
        return {
            ax: (float(self.axes[ax].min()), float(self.axes[ax].max()))
            for ax in AXIS_ORDER
        }

    @property
    def source(self) -> str:
        return SOURCE


def _resolve(filter_label: str):
    """``(svo id, mist name, facility)`` of a band's ``filter:`` label through
    the alias table, or ``(None, reason)``."""
    alias_df = _load_alias_table()
    if alias_df is None:
        raise RuntimeError(
            "the filter alias table (filters/filternames.txt) is missing, so "
            f"filter {filter_label!r} cannot be mapped to a limb-darkening table."
        )
    label = AMBIGUOUS_FILTER_ALIASES.get(filter_label, filter_label)
    rows = alias_df[alias_df.eq(label).any(axis=1)]
    if rows.empty:
        return None, (
            f"filter {filter_label!r} is not in the filter alias table "
            f"(filters/filternames.txt), so there is no PHOENIX limb-darkening "
            f"table for it (spell the filter as the alias table does)"
        )
    svo = resolve_filter_name(label, alias_df, alias="SVO")
    mist = resolve_filter_name(label, alias_df, alias="MIST")
    try:
        fac = facility_from_svo_name(svo)
    except Exception as exc:  # the facility map is a short prefix table
        return None, f"filter {filter_label!r} ({svo}): {exc}"
    return (svo, mist, fac), None


def ld_table_lookup(
    filter_label: str, law: str, model_root: Path | str | None = None
) -> Tuple[Optional[str], Optional[str]]:
    """``(MIST filter name, None)`` when a PHOENIX table holds the law's
    coefficients for this filter, or ``(None, why not)``."""
    if law not in LAWS:
        return (
            None,
            f"no PHOENIX limb-darkening tables exist for the {law!r} law",
        )
    resolved, problem = _resolve(filter_label)
    if resolved is None:
        return None, problem
    svo, mist, fac = resolved
    path = ld_table_path(_root(model_root), law, fac)
    if not path.is_file():
        return None, (
            f"the PHOENIX {law} limb-darkening table for facility {fac} "
            f"({path.name}) is not present; generate it with "
            f"models/PHOENIX/generate_PHOENIX_LD_Tables.py or fetch the "
            f"published set"
        )
    wanted = [coefficient_column(mist, law, c) for c in COEFFICIENTS[law]]
    have = set(bc_table_filter_columns(path))
    missing = [c for c in wanted if c not in have]
    if missing:
        return None, (
            f"the PHOENIX {law} table {path.name} has no column(s) {missing} "
            f"for filter {filter_label!r} ({svo}); its wavelength range may "
            f"lie outside the intensity spectra's 500-26000 A"
        )
    return mist, None


def load_ld_table(
    filter_label: str, law: str, model_root: Path | str | None = None
) -> LDTable:
    """Read one filter's coefficients and reshape them onto the complete
    box of the table.  Raises ``ValueError`` naming the reason when there
    is no such table."""
    mist, problem = ld_table_lookup(filter_label, law, model_root)
    if mist is None:
        raise ValueError(f"{filter_label!r}: {problem}")
    svo, _mist, fac = _resolve(filter_label)[0]
    path = ld_table_path(_root(model_root), law, fac)
    cols = [coefficient_column(mist, law, c) for c in COEFFICIENTS[law]]
    df = read_bc_table(path)
    box = complete_axes(df, cols)
    axes = {
        ax: np.asarray(box[_AXIS_KEY[ax]], dtype=float) for ax in AXIS_ORDER
    }
    index = pd.MultiIndex.from_product(
        [axes["teff"], axes["logg"], axes["feh"], axes["av"]],
        names=GRID_KEY_COLS,
    )
    keyed = df.set_index(GRID_KEY_COLS)
    keyed = keyed[~keyed.index.duplicated()]
    shape = tuple(len(axes[ax]) for ax in AXIS_ORDER)
    values = np.empty(shape + (len(cols),))
    for k, c in enumerate(cols):
        col = keyed[c].reindex(index)
        if col.isna().any():
            raise ValueError(
                f"{path}: column {c} is incomplete inside its own complete "
                f"box -- the table is corrupt or the box computation drifted"
            )
        values[..., k] = col.values.reshape(shape)
    return LDTable(
        band=filter_label,
        law=law,
        columns=tuple(COEFFICIENTS[law]),
        axes=axes,
        values=values,
        meta=df.attrs.get("meta", {}),
        path=path,
        facility=fac,
        mist_name=mist,
    )


def interpolate(table: LDTable, teff, logg, feh, av) -> np.ndarray:
    """Coefficients at one point, in ``table.columns`` order -- numpy.

    Linear in every axis with linear extrapolation off the edge cell, the
    same rule as ``interpolate_node`` (and the BC grid), so a start seeded
    from this is what the model computes there.  Used for start values.
    """
    rgi = _ScipyRGI(
        [table.axes[ax] for ax in AXIS_ORDER],
        table.values,
        method="linear",
        bounds_error=False,
        fill_value=None,
    )
    return np.asarray(rgi([[teff, logg, feh, av]])[0], dtype=float)


def interpolate_node(table: LDTable, teff, logg, feh, av):
    """Coefficients as a PyTensor vector, in ``table.columns`` order, at
    scalar tensors (one star); extrapolates linearly off the box, which
    the bounds Band injects hold the star inside."""
    interp = RegularGridInterpolator(
        points=[table.axes[ax] for ax in AXIS_ORDER],
        values=table.values,
    )
    coords = pt.stack([teff, logg, feh, av])[None, :]
    return interp.evaluate(coords)[0]
