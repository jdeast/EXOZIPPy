"""Pecaut & Mamajek's mean dwarf sequence as a Teff(M) and R(M) prior.

The lookup ``components/star/mamajek.py`` already ships (the getstar.pro
port of EXOFASTv2, table EEM_dwarf_UBVIJHK_colors_Teff.txt v2022.04.16; cite
Pecaut & Mamajek 2013, ApJS 208, 9).  This module puts two of its columns
into the PyTensor graph: log10 Teff and log10 R as functions of log10 M,
for main-sequence stars from the hydrogen-burning limit to 1.5 solMass.

WHY A TABLE AND NOT A POLYNOMIAL.  The dwarf sequence has real structure
(the Teff-mass relation is nearly flat below 0.4 solMass and steep above
0.6), and a degree-5 or -6 polynomial in log M still misses the table by
3-9%.  So the table is resampled onto a uniform grid in log10 M at import
(``_N`` knots, numpy interpolation of the shipped rows) and evaluated in
the graph by piecewise-linear interpolation: exact at the knots, continuous,
differentiable except at knots, and clamped -- flat -- outside the mass
range, matching getstar.pro's "will not extrapolate" clamp.  The grid was
generated from the shipped table by the recipe recorded below;
tests/test_mamajek_relation.py evaluates the graph at the table's own rows
and compares.

Recipe: read_mamajek(minmass=0.078); rows with finite Msun, Teff, R_Rsun and
0.078 <= Msun <= 1.5; sorted by mass, duplicate masses dropped;
np.interp of log10(Teff) and log10(R_Rsun) onto linspace(log10 Mmin,
log10 Mmax, 401).
"""

