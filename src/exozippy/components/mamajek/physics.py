def _interp(logmass, table):
    """Piecewise-linear interpolation of ``table`` at ``logmass``, clamped."""
    xi = pt.clip((logmass - _X0) / _DX, 0.0, _N - 1.0 - 1e-9)
    i0 = pt.cast(pt.floor(xi), "int64")
    frac = xi - pt.cast(i0, "float64")
    tab = pt.as_tensor_variable(table)
    return tab[i0] * (1.0 - frac) + tab[i0 + 1] * frac


