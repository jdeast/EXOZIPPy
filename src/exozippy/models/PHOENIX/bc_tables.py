"""The published PHOENIX bolometric-correction tables, with a lazy fetch.

The per-facility ``BCs/{FACILITY}.bc.parquet`` tables an SED with
``model: PHOENIX`` reads are generated by ``generate_PHOENIX_LD_Tables.py
--products bc`` (one stream of the PHOENIX-ACES archive, which is never
rehosted) and published on Zenodo as record ``phoenix_bc_tables`` in
``utilities/zenodo_assets.py``.  The rules are the NextGen tables'
(``models/NextGen/bc_tables.py``, whose docstring has the reasons):
fetched per facility on first use, into the DEFAULT model root only; a
present table checked against its pinned size and md5 once per process; a
local edit never overwritten, a previous published version re-fetched;
every failure a RuntimeError naming the file, the record and the way out
(never a FileNotFoundError, which the SED reads as "this model has no
tables").

Until the record is published it is PENDING in the registry, and asking
for a table raises saying so.  Tables generated locally are used through
an explicit ``model_root:`` (a tree holding ``PHOENIX/BCs/``), which is
never fetched into.

    exozippy-fetch-phoenix-bc-tables     # every table, for offline use
"""

from __future__ import annotations

import argparse
import hashlib
import logging
import urllib.error
from pathlib import Path
from typing import Dict, List, Sequence

from ...utilities import zenodo, zenodo_assets

logger = logging.getLogger(__name__)

try:
    current_dir = Path(__file__).parent
except NameError:  # pragma: no cover - interactive use only
    current_dir = Path.cwd()

# Where bc_grid.bc_table_path puts the default root's PHOENIX tables,
# beside the tracked PHOENIX.grid.yaml, PHOENIX.magsys.csv and plot.py.
BC_TABLE_DIR = current_dir / "BCs"

RECORD_NAME = "phoenix_bc_tables"
FETCH_COMMAND = "exozippy-fetch-phoenix-bc-tables"
_SUFFIX = ".bc.parquet"

# (path, size, mtime_ns, inode) of tables already md5-verified this process.
_verified: set[tuple[str, int, int, int]] = set()


def _record() -> zenodo_assets.ZenodoRecord:
    """The pinned record; a RuntimeError naming the way out while it is
    pending (RecordPendingError is a LookupError, which no reader of the
    tables should mistake for "no such facility")."""
    try:
        return zenodo_assets.record(RECORD_NAME)
    except zenodo_assets.RecordPendingError as e:
        raise RuntimeError(
            f"The PHOENIX bolometric-correction tables are not published "
            f"yet ({e}).  Fit with the default `model: NextGen` in the SED "
            f"file, or generate the tables yourself and point the SED's "
            f"`model_root:` at the tree that holds PHOENIX/BCs/ (an explicit "
            f"root is used as given and never fetched into)."
        ) from None


def _table_files() -> Dict[str, Dict]:
    """{filename: {"size", "md5"}} of every published table (the record
    also carries the publish script's MANIFEST.txt, which is never
    fetched)."""
    return {
        name: {"size": pin.size, "md5": pin.md5}
        for name, pin in _record().files.items()
        if name.endswith(_SUFFIX)
    }


def published_tables() -> List[str]:
    """Filenames of every published table, sorted."""
    return sorted(_table_files())


def record_url() -> str:
    return _record().record_url


def _md5(path: Path) -> str:
    h = hashlib.md5()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _check_present(path: Path, name: str, files: Dict[str, Dict]) -> bool:
    """True when the table at `path` is the pin; False when it is a
    PREVIOUS published version (the caller re-fetches over it); raises on
    anything else -- a local edit is never overwritten."""
    meta = files[name]
    st = path.stat()
    key = (str(path), st.st_size, st.st_mtime_ns, st.st_ino)
    if key in _verified:
        return True
    md5 = None
    if st.st_size != meta["size"] or (md5 := _md5(path)) != meta["md5"]:
        superseded = set(_record().superseded.get(name, ()))
        if (md5 or _md5(path)) in superseded:
            logger.debug(
                "%s is a previous published version of %s; fetching the "
                "pinned one (record %s) over it.",
                path,
                name,
                record_url(),
            )
            return False
        raise RuntimeError(
            f"{path} is not the published {name} (pinned size "
            f"{meta['size']}, md5 {meta['md5']}; record {record_url()}). "
            f"It was most likely regenerated locally "
            f"(generate_PHOENIX_LD_Tables.py merges into it). It is NOT "
            f"overwritten. Either publish it as a new version of the Zenodo "
            f"record and update the pins in utilities/zenodo_assets.py, or "
            f"move it aside and re-run to fetch the published table. To fit "
            f"against a modified table deliberately, copy the PHOENIX/ tree "
            f"elsewhere and point the SED's `model_root:` at the copy."
        )
    _verified.add(key)
    return True


def ensure_tables(
    filenames: Sequence[str] | None = None,
    dest_dir: Path | str | None = None,
    allow_local_changes: bool = False,
) -> List[Path]:
    """Make sure the named published tables are on disk; return their paths.

    ``filenames`` None means every published table; a name that is not
    published raises KeyError (bc_grid asks only for published ones).
    ``allow_local_changes`` accepts a present table that differs from the
    pin (the generator's own merges).  Raises RuntimeError while the record
    is pending, for a present table that differs from the pin, and for an
    absent one that cannot be fetched.
    """
    files = _table_files()
    dest_dir = BC_TABLE_DIR if dest_dir is None else Path(dest_dir)
    names = sorted(files) if filenames is None else list(filenames)
    unknown = [n for n in names if n not in files]
    if unknown:
        raise KeyError(
            f"{unknown} are not published PHOENIX BC tables; published: "
            f"{sorted(files)}"
        )
    missing = []
    for name in names:
        path = dest_dir / name
        if path.is_file():
            if not allow_local_changes and not _check_present(
                path, name, files
            ):
                path.unlink()
                missing.append(name)
        else:
            missing.append(name)
    if missing:
        assets = {
            n: {**files[n], "url": f"{record_url()}/files/{n}"}
            for n in missing
        }
        try:
            zenodo.fetch_assets(assets, dest_dir)
        except (RuntimeError, urllib.error.URLError, OSError) as e:
            raise RuntimeError(
                f"Could not fetch the PHOENIX BC table(s) {missing} into "
                f"{dest_dir} from Zenodo record {record_url()}: {e}. "
                f"Pre-fetch them on a machine with network access with "
                f"`{FETCH_COMMAND}`; the machine cache it fills then serves "
                f"every checkout on this machine."
            ) from e
        for name in missing:
            path = dest_dir / name
            st = path.stat()
            _verified.add((str(path), st.st_size, st.st_mtime_ns, st.st_ino))
    return [dest_dir / n for n in names]


def fetch_all(dest_dir: Path | str | None = None) -> List[Path]:
    """Fetch every published table (the owner hook for the record)."""
    return ensure_tables(None, dest_dir=dest_dir)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog=FETCH_COMMAND,
        description=(
            "Download (or link from the machine cache) every published "
            "PHOENIX bolometric-correction table, so SED fits with "
            "`model: PHOENIX` can run offline afterwards."
        ),
    )
    parser.add_argument(
        "--dest",
        default=None,
        help=f"destination directory (default: {BC_TABLE_DIR})",
    )
    args = parser.parse_args(argv)
    paths = fetch_all(args.dest)
    total = sum(p.stat().st_size for p in paths)
    print(
        f"{len(paths)} PHOENIX BC tables ({total / 1e6:.1f} MB) present in "
        f"{paths[0].parent}"
    )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
